// @ts-check
/**
 * Hostinger (Apache/LiteSpeed) output for the static build:
 *   - dist/.htaccess: HTTPS + canonical host, legacy 301s, /api rewrites, custom 404,
 *     security headers, HTML revalidation, private files blocked
 *   - dist/_astro/.htaccess: long-lived immutable caching for hashed assets
 * The redirect table comes from /build-redirects.json (generated from content), which is
 * deleted after use so it never ships.
 */
import { readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

/** @param {string} p */
const escapeRegex = (p) => p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** @returns {import('astro').AstroIntegration} */
export default function hostinger({ productionHost = 'hyderabadcampersclubhcc.in' } = {}) {
  /** @type {URL} */
  let site;
  return {
    name: 'hcc-hostinger',
    hooks: {
      'astro:config:done': ({ config }) => {
        site = new URL(config.site ?? `https://${productionHost}`);
      },
      'astro:build:done': async ({ dir, logger }) => {
        const out = fileURLToPath(dir);
        const tableFile = path.join(out, 'build-redirects.json');
        /** @type {{from: string, to: string}[]} */
        let redirects = [];
        try {
          redirects = JSON.parse(await readFile(tableFile, 'utf8'));
          await rm(tableFile);
        } catch {
          logger.warn('build-redirects.json not found; .htaccess written without legacy redirects');
        }

        const host = site.hostname;
        const isProd = host === productionHost;
        const canonical = isProd
          ? [
              '# HTTPS + canonical host (non-www)',
              'RewriteCond %{HTTPS} !=on [OR]',
              `RewriteCond %{HTTP_HOST} ^www\\.${escapeRegex(productionHost)}$ [NC]`,
              `RewriteRule ^ https://${productionHost}%{REQUEST_URI} [L,R=301]`,
            ]
          : ['# HTTPS', 'RewriteCond %{HTTPS} !=on', 'RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]'];

        const legacy = redirects.map(
          ({ from, to }) => `RewriteRule ^${escapeRegex(from.replace(/^\//, '').replace(/\/$/, ''))}/?$ ${to} [R=301,L]`,
        );

        const htaccess = `# Generated by integrations/hostinger.mjs: do not edit on the server.
Options -Indexes -MultiViews
DirectoryIndex index.html index.php
ErrorDocument 404 /404.html

AddType image/avif .avif
AddType image/webp .webp
AddType font/woff2 .woff2
AddType application/manifest+json .webmanifest

<IfModule mod_rewrite.c>
RewriteEngine On
RewriteBase /

${canonical.join('\n')}

# Enquiry endpoint + CMS login (PHP)
RewriteRule ^api/intents/?$ api/intents.php [L]
RewriteRule ^api/decap-auth/?$ api/decap-auth.php [L,QSA]

# Legacy WordPress URLs -> new pages (${legacy.length} rules)
${legacy.join('\n')}

# Old WordPress endpoints that bots keep requesting
RewriteRule ^(wp-admin|wp-login\\.php|xmlrpc\\.php|wp-json)(/.*)?$ - [R=410,L]
</IfModule>

# Never serve secrets, lead backups or source maps
<FilesMatch "^(config\\.php|config\\.sample\\.php|.*\\.jsonl|.*\\.map)$">
  Require all denied
</FilesMatch>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(self)"
  Header always set Strict-Transport-Security "max-age=31536000"
  <FilesMatch "\\.(html|xml|txt|json)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  <FilesMatch "\\.(svg|ico|png|jpg|jpeg|webp|avif)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json image/svg+xml
</IfModule>
`;
        await writeFile(path.join(out, '.htaccess'), htaccess);

        // Hashed build assets never change: cache for a year.
        await mkdir(path.join(out, '_astro'), { recursive: true });
        await writeFile(
          path.join(out, '_astro', '.htaccess'),
          '<IfModule mod_headers.c>\n  Header set Cache-Control "public, max-age=31536000, immutable"\n</IfModule>\n',
        );
        logger.info(`.htaccess written for ${host} (${legacy.length} legacy redirects)`);
      },
    },
  };
}
